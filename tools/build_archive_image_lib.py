# in scipy/numba and can fail to import under a mismatched numpy, which must not
# block runs that have no embeddings (SigLIP is optional; the gallery greys it out).
def _prep_rasterfairy() -> None:
    """rasterfairy doesn't fully self-init under modern numpy; replicate the dance
    from embed_and_visualize.py: (a) attach the `prime` submodule onto the
    rasterfairy.rasterfairy module (its code references `prime.Prime()` without
    importing it), and (b) restore deprecated numpy aliases the library still uses."""
    rf_module = importlib.import_module("rasterfairy.rasterfairy")
    prime_module = importlib.import_module("rasterfairy.prime")
    rf_module.prime = prime_module
    for alias, t in (("float", float), ("int", int), ("bool", bool)):
        if not hasattr(np, alias):
            setattr(np, alias, t)


