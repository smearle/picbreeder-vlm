"""
Build a per-archive image library + layout JSON for one (config, seed) pair,
for the blog post's "click again to zoom to native" view.

For one archive run we emit, under <ASSETS>/<arc>_s<N>_lib/:
  thumbs/img_NNNNNN.webp  -- 3000+ color WebP thumbs, one per published image (--grayscale to flatten)
  layout.json             -- per-image (row, col) for {chronological, siglip}
                             plus the dims of each grid

The chronological layout is read from <run>/archive/archive_grid.json (already
generated by the eval pipeline). The SigLIP layout is re-derived from the
cached SigLIP-2 embeddings under <run>/embeddings_openclip_SigLIP2-B-alignet.npz
by running umap.UMAP() (matching the params in embed_and_visualize.py) and
then snapping with rasterfairy <https://github.com/Quasimondo/RasterFairy>.

Prototype: this is currently called only for default_s4 to validate the UX.
If it works we'll loop over the other 41 (config, seed) pairs.

Usage:
    python tools/build_archive_image_lib.py default_s4
    python tools/build_archive_image_lib.py default_s4 --force
"""
